#!/bin/bash
set -u
source /app/functions.sh

[[ ${DEBUG:-false} == true ]] && set -x

check_writable_directory() {
    local dir="$1"
    if [[ ! -d "$dir" ]]; then
        err "can't access the '$dir' directory. Check that it is declared as a writable volume."
        exit 1
    fi
    if ! touch "$dir/.check_writable" 2>/dev/null; then
        err "can't write to the '$dir' directory. Check that it is exported as a writable volume."
        exit 1
    fi
    rm -f "$dir/.check_writable"
}

check_writable_directory "$CERT_DIR"
check_writable_directory "$LE_DIR"
check_writable_directory "$VHOST_DIR"
check_writable_directory "$WEBROOT"

ensure_dhparam
ensure_default_cert
configure_waf

if [[ -n "${DEFAULT_EMAIL:-}" ]] && ! is_email "$DEFAULT_EMAIL"; then
    err "DEFAULT_EMAIL '$DEFAULT_EMAIL' is not a valid e-mail address; certificates without rap.le_email will fail"
fi

# Serve every certificate that already exists in the /etc/letsencrypt volume.
# The host list itself is (re)generated by the rancher-gen service as soon as
# it starts, and its notify command issues whatever is still missing.
rm -f "$LE_CONF"
relink_existing_lineages
remove_all_location_configurations

# Never leave the image's default site around.
rm -f /etc/nginx/conf.d/default.conf

# Certificate renewal schedule (crond runs under forego, see Procfile).
: "${CRON:=0 2 * * *}"
if [[ $CRON =~ ^[-0-9*/,[:space:]]+$ ]]; then
    printf '%s /app/renew.sh\n' "$CRON" > /etc/crontabs/root
    chmod 0600 /etc/crontabs/root
else
    err "CRON='$CRON' is not a valid 5-field cron expression; renewal disabled"
    : > /etc/crontabs/root
fi

exec "$@"
